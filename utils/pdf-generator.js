/**
 * Invoice PDF generation using jsPDF.
 */
export async function generateInvoicePDF(invoice, options = {}) {
  const { jsPDF } = await import('https://cdn.jsdelivr.net/npm/jspdf@2.5.1/+esm');
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });

  const shop = invoice.shop || {};
  const customer = invoice.customer || {};
  const items = invoice.items || [];
  const margin = 15;
  let y = margin;

  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text('INVOICE', margin, y);
  y += 10;

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(shop.name || 'Shop', margin, y);
  y += 5;
  if (shop.address) { doc.text(shop.address, margin, y); y += 5; }
  if (shop.mobile) { doc.text(`Mobile: ${shop.mobile}`, margin, y); y += 5; }
  if (shop.email) { doc.text(`Email: ${shop.email}`, margin, y); y += 5; }
  if (shop.gstNumber) { doc.text(`GST: ${shop.gstNumber}`, margin, y); y += 5; }

  doc.setFont('helvetica', 'bold');
  doc.text(`Invoice #: ${invoice.invoiceNumber}`, 140, margin);
  doc.setFont('helvetica', 'normal');
  doc.text(`Date: ${formatPdfDate(invoice.createdAt)}`, 140, margin + 5);

  y += 10;
  doc.setDrawColor(200);
  doc.line(margin, y, 195, y);
  y += 8;

  doc.setFont('helvetica', 'bold');
  doc.text('Bill To:', margin, y);
  y += 5;
  doc.setFont('helvetica', 'normal');
  doc.text(customer.name || 'Walk-in Customer', margin, y);
  y += 5;
  if (customer.mobile) { doc.text(`Mobile: ${customer.mobile}`, margin, y); y += 5; }

  y += 5;
  doc.setFont('helvetica', 'bold');
  doc.text('Item', margin, y);
  doc.text('Qty', 100, y);
  doc.text('Price', 130, y);
  doc.text('Total', 165, y);
  y += 3;
  doc.line(margin, y, 195, y);
  y += 6;

  doc.setFont('helvetica', 'normal');
  items.forEach((item) => {
    const name = getItemName(item);
    const qty = item.quantity || 1;
    const price = Number(item.price) || 0;
    const total = qty * price;

    if (y > 260) {
      doc.addPage();
      y = margin;
    }

    doc.text(String(name).substring(0, 40), margin, y);
    doc.text(String(qty), 100, y);
    doc.text(price.toFixed(2), 130, y);
    doc.text(total.toFixed(2), 165, y);
    y += 6;
  });

  y += 5;
  doc.line(margin, y, 195, y);
  y += 8;

  const subtotal = invoice.subtotal ?? invoice.grandTotal ?? 0;
  const taxAmount = invoice.taxAmount ?? 0;
  const grandTotal = invoice.grandTotal ?? subtotal + taxAmount;

  doc.text(`Subtotal:`, 130, y);
  doc.text(subtotal.toFixed(2), 165, y);
  y += 6;
  if (taxAmount > 0) {
    doc.text(`Tax (${invoice.taxRate || 0}%):`, 130, y);
    doc.text(taxAmount.toFixed(2), 165, y);
    y += 6;
  }
  doc.setFont('helvetica', 'bold');
  doc.text('Grand Total:', 130, y);
  doc.text(grandTotal.toFixed(2), 165, y);

  if (options.showManager && invoice.manager) {
    y += 12;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.text(`Manager: ${invoice.manager.name || ''}`, margin, y);
    if (invoice.manager.mobile) {
      doc.text(`Mobile: ${invoice.manager.mobile}`, margin, y + 4);
    }
  }

  doc.setFontSize(8);
  doc.setTextColor(120);
  doc.text('Generated by KING BUSINESS ANALYTICS', margin, 285);

  return doc;
}

function getItemName(item) {
  return item.productName || item.medicineName || item.itemName ||
    item.serviceName || item.bookTitle || item.name || 'Item';
}

function formatPdfDate(date) {
  const d = date?.toDate ? date.toDate() : new Date(date);
  return d.toLocaleDateString('en-IN');
}

export async function downloadInvoicePDF(invoice, filename, options) {
  const doc = await generateInvoicePDF(invoice, options);
  doc.save(filename || `invoice-${invoice.invoiceNumber}.pdf`);
}

export async function printInvoicePDF(invoice, options) {
  const doc = await generateInvoicePDF(invoice, options);
  doc.autoPrint();
  window.open(doc.output('bloburl'), '_blank');
}
